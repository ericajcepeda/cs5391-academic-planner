// Optional browser smoke test: npm install playwright, then node planner_browser_tests.js
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const server = http.createServer((req, res) => {
    const name = req.url === '/' ? 'index.html' : req.url.slice(1);
    if (!['index.html', 'styles.css', 'sprint2_ui.css', 'sprint3_ui.css', 'calendar_views.css', 'calendar_views.js', 'planner_logic.js', 'lain_planner_logic.js', 'planner_validation.js', 'planner_extras.js', 'planner_extras.css'].includes(name)) { res.writeHead(404).end(); return; }
    res.setHeader('Content-Type', name.endsWith('.js') ? 'text/javascript' : name.endsWith('.css') ? 'text/css' : 'text/html');
    res.end(fs.readFileSync(path.join(__dirname, name)));
});
(async () => {
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox'] });
    try {
        const page = await browser.newPage({ timezoneId: 'America/Chicago', viewport: { width: 390, height: 844 } });
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(`http://127.0.0.1:${server.address().port}/`);
        page.once('dialog', dialog => dialog.dismiss());
        await page.locator('#sample-button').click();
        assert.equal(await page.locator('.task-card').count(), 0);
        page.once('dialog', dialog => dialog.accept());
        await page.locator('#sample-button').click();
        assert.equal(await page.locator('.task-card').count(), 2);
        await page.locator('[data-view="month"]').click();
        assert.ok(await page.locator('.month-date').count() >= 28);
        await page.locator('.month-date.is-today').click();
        assert.equal(await page.locator('.day-view').count(), 1);
        await page.locator('[data-view="week"]').click();
        await page.locator('[data-week="7"]').click();
        assert.equal(await page.locator('#next-week').isDisabled(), true);
        await page.locator('#add-task').click();
        await page.locator('#save-task').click();
        assert.equal(await page.locator('#task-title-error').isVisible(), true);
        await page.locator('#task-title').fill('Review sprint');
        await page.locator('#task-course').fill('CS 5391');
        await page.locator('#task-priority').selectOption('high');
        const today = await page.evaluate(() => PlannerRules.localDate(new Date()));
        await page.locator('#task-due-date').fill(today);
        await page.locator('#save-task').click();
        assert.equal(await page.locator('#task-editor').isVisible(), false);
        assert.equal(await page.locator('#week-heading').innerText(), 'Week 8 of 8');
        assert.equal(await page.locator('.task-card').count(), 3);
        await page.locator('#course-filter').selectOption('cs 5391');
        assert.equal(await page.locator('.task-card').count(), 1);
        await page.locator('#priority-filter').selectOption('low');
        assert.equal(await page.locator('.task-card').count(), 0);
        await page.locator('#priority-filter').selectOption('high');
        assert.equal(await page.locator('.task-card').count(), 1);
        await page.locator('#task-search').fill('no match');
        assert.equal(await page.locator('.planner-empty').isVisible(), true);
        await page.locator('#task-search').fill('sprint');
        await page.getByLabel('Status for Review sprint').selectOption('Completed');
        await page.locator('#completed-filter').click();
        assert.equal(await page.locator('.task-card').count(), 1);
        await page.getByRole('button', { name: 'Edit Review sprint' }).click();
        await page.locator('#task-title').fill('Sprint evidence');
        await page.locator('#save-task').click();
        await page.locator('#task-search').fill('evidence');
        assert.equal(await page.locator('.task-card h3').innerText(), 'Sprint evidence');
        await page.reload();
        assert.equal(await page.getByLabel('Status for Sprint evidence').inputValue(), 'Completed');
        page.once('dialog', dialog => dialog.dismiss());
        await page.getByRole('button', { name: 'Delete Sprint evidence' }).click();
        assert.equal(await page.locator('.task-card').count(), 3);
        page.once('dialog', dialog => dialog.accept());
        await page.getByRole('button', { name: 'Delete Sprint evidence' }).click();
        assert.equal(await page.locator('.task-card').count(), 2);
        page.once('dialog', dialog => dialog.dismiss());
        await page.locator('#reset-button').click();
        assert.equal(await page.locator('.task-card').count(), 2);
        page.once('dialog', dialog => dialog.accept());
        await page.locator('#reset-button').click();
        assert.equal(await page.locator('.task-card').count(), 0);
        assert.equal(await page.locator('#prev-week').isDisabled(), true);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        assert.deepEqual(errors, []);
        console.log('PASS: browser CRUD, validation, persistence, filters, navigation, confirmations, mobile width, and no JS errors.');
    } finally { await browser.close(); server.close(); }
})().catch(error => { console.error(error); server.close(); process.exitCode = 1; });
